#!/usr/bin/env python3
"""Emit src/rubik/ida-tables.S from src/rubik/ida-tables.h.

The C and the assembly implementations are linked separately, so the
assembly needs its own copy of the IDA* tables. Usage:
    python3 mytests/gen-ida-tables-asm.py src/rubik/ida-tables.h > src/rubik/ida-tables.S
"""
import re
import sys

src = open(sys.argv[1]).read()


def values(name):
    m = re.search(name + r"[^=]*=\s*\{(.*?)\};", src, re.S)
    return [int(v) for v in re.findall(r"\d+", m.group(1))]


def emit(label, directive, data, per_line):
    print(f"    .globl  {label}")
    print(f"{label}:")
    for i in range(0, len(data), per_line):
        print(f"    {directive} " + ", ".join(str(v) for v in data[i:i + per_line]))
    print()


print("# Generated by mytests/gen-ida-tables-asm.py from ida-tables.h. Do not edit.")
print("#")
print("# Copy of the IDA* tables for rubik_solve_asm: the transitions of the")
print("# permutation (3 x 5040) and orientation (3 x 729) coordinates for a quarter")
print("# turn of R, B and D, and the two pattern database distances.")
print()
print("    .section .rodata")
print("    .align  2")
emit("rubik_asm_perm_move", ".half", values("ida_permutation_transition"), 12)
emit("rubik_asm_orient_move", ".half", values("ida_orientation_transition"), 12)
emit("rubik_asm_perm_dist", ".byte", values("ida_permutation_distance"), 24)
emit("rubik_asm_orient_dist", ".byte", values("ida_orientation_distance"), 24)
